CREATE OR REPLACE FUNCTION public.cleanup_old_notifications()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
  -- Delete notifications older than their expiration date
  DELETE FROM public.admin_notifications
  WHERE expires_at IS NOT NULL 
    AND expires_at < NOW();
  
  -- Archive read notifications older than 90 days
  UPDATE public.admin_notifications
  SET is_archived = true
  WHERE is_read = true
    AND read_at < NOW() - INTERVAL '90 days'
    AND is_archived = false;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.collect_system_health_metrics()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
BEGIN
  -- Clear old metrics (keep last 30 days)
  DELETE FROM public.system_health_metrics 
  WHERE collected_at < NOW() - INTERVAL '30 days';
  
  -- Collect database metrics
  INSERT INTO public.system_health_metrics (metric_name, metric_value, metric_unit, category)
  SELECT 
    'database_size_mb',
    pg_database_size(current_database()) / 1024.0 / 1024.0,
    'megabytes',
    'database';
    
  INSERT INTO public.system_health_metrics (metric_name, metric_value, metric_unit, category)
  SELECT 
    'active_connections',
    count(*),
    'count',
    'database'
  FROM pg_stat_activity 
  WHERE state = 'active';
  
  -- Collect business metrics
  INSERT INTO public.system_health_metrics (metric_name, metric_value, metric_unit, category)
  SELECT 
    'total_products',
    count(*),
    'count',
    'business'
  FROM public.products 
  WHERE status = 'active';
  
  INSERT INTO public.system_health_metrics (metric_name, metric_value, metric_unit, category)
  SELECT 
    'total_orders_today',
    count(*),
    'count',
    'business'
  FROM public.orders 
  WHERE created_at >= CURRENT_DATE;
  
  INSERT INTO public.system_health_metrics (metric_name, metric_value, metric_unit, category)
  SELECT 
    'total_customers',
    count(*),
    'count',
    'business'
  FROM public.profiles;
  
  INSERT INTO public.system_health_metrics (metric_name, metric_value, metric_unit, category)
  SELECT 
    'low_stock_products',
    count(*),
    'count',
    'inventory'
  FROM public.products 
  WHERE inventory_quantity <= 5 AND track_inventory = true;
  
END;
$function$
;

CREATE OR REPLACE FUNCTION public.decrease_product_stock(product_id uuid, quantity integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
  -- Update both inventory fields for compatibility
  UPDATE products 
  SET 
    inventory_quantity = GREATEST(0, inventory_quantity - quantity),
    stock_quantity = GREATEST(0, COALESCE(stock_quantity, inventory_quantity) - quantity),
    updated_at = NOW()
  WHERE id = product_id;
  
  -- Log the stock change for audit purposes
  INSERT INTO stock_movements (
    product_id,
    movement_type,
    quantity,
    reason,
    created_at
  ) VALUES (
    product_id,
    'decrease',
    quantity,
    'order_completed',
    NOW()
  );
EXCEPTION
  WHEN OTHERS THEN
    -- Log error but don't fail the transaction
    RAISE WARNING 'Error updating stock for product %: %', product_id, SQLERRM;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.generate_ticket_number()
 RETURNS text
 LANGUAGE plpgsql
AS $function$
DECLARE
  ticket_number TEXT;
  counter INTEGER;
BEGIN
  -- Get current year and month
  SELECT 
    'TKT-' || 
    to_char(NOW(), 'YYYY') || 
    to_char(NOW(), 'MM') || 
    '-' || 
    LPAD((
      SELECT COUNT(*) + 1 
      FROM public.support_tickets 
      WHERE DATE_TRUNC('month', created_at) = DATE_TRUNC('month', NOW())
    )::TEXT, 4, '0')
  INTO ticket_number;
  
  RETURN ticket_number;
END;
$function$
